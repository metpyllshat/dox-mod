def p_xml(style, text):
    style_id = {"title": "Title", "h1": "Heading1", "h2": "Heading2", "p": "Normal", "li": "List"}.get(style, "Normal")
    body = escape(text)
    return (
        f'<w:p><w:pPr><w:pStyle w:val="{style_id}"/></w:pPr>'
        f'<w:r><w:t xml:space="preserve">{body}</w:t></w:r></w:p>'
    )


